-- 迁移：把「默认走 IPv6」存到节点上
--
-- 只对**已经跑起来的库**需要。新库直接用 sql/init.sql，那里已经有这一列。
--
-- 背景：建节点的表单上有一个「默认走 IPv6」开关，请求里也带着它，但创建从来不把它存
-- 下来——它只活在创建对话框的内存里，交给当场弹出的那条安装命令。之后从节点列表再打开
-- 同一个节点的安装命令时，没有任何地方知道该不该加 --prefer-ipv6，于是同一个节点从两个
-- 入口会拿到两条不同的命令，照后一条装出来的 agent 注册的是 IPv4 地址。
--
-- 存量行一律视为没勾（default 0）：这个选择以前没有存过，现在也无从倒推——已经注册过的
-- 节点看 ip 是不是等于 ipv6 只能猜，没注册过的节点连线索都没有。

alter table nodes
    add column prefer_ipv6 tinyint(1) not null default 0 comment '建节点时勾的「默认走 IPv6」';

-- 执行完在开发库上跑一次 `stander gen` 重新生成产物（docs/development.md 的第三步）。
